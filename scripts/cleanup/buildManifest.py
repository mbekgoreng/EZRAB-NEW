import os, json, hashlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

def sha256(p):
    try:
        h = hashlib.sha256()
        with open(p, 'rb') as fh:
            for c in iter(lambda: fh.read(1 << 20), b''):
                h.update(c)
        return h.hexdigest()
    except OSError:
        return None

def size_of(p):
    if os.path.isfile(p):
        return os.path.getsize(p)
    if os.path.isdir(p):
        t = 0
        for dp, dn, fn in os.walk(p):
            for f in fn:
                try:
                    t += os.path.getsize(os.path.join(dp, f))
                except OSError:
                    pass
        return t
    return 0

def count_of(p):
    if os.path.isfile(p):
        return 1
    if os.path.isdir(p):
        n = 0
        for dp, dn, fn in os.walk(p):
            n += len(fn)
        return n
    return 0

