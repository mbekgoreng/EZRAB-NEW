def main():
    # Root QA screenshots: unreferenced transient test evidence
    listed = {p.replace('\\', '/') for p, *_ in ENTRIES}
    root_imgs = []
    for f in os.listdir(ROOT):
        if os.path.isfile(os.path.join(ROOT, f)) and f.lower().endswith(('.png', '.jpg', '.jpeg')):
            if f not in listed:
                root_imgs.append(f)
    for f in sorted(root_imgs):
        ENTRIES.append((f, 'G_TEMPORARY', 'Root-level QA/browser-proof screenshot or scratch render. Not embedded in any markdown, not imported by code.', [], 0.95))

    manifest = []
    total = 0
    for path, cat, reason, refs, conf in ENTRIES:
        ap = os.path.join(ROOT, path)
        if not os.path.exists(ap):
            continue
        s = size_of(ap)
        total += s
        entry = {
            'path': path.replace('\\', '/'),
            'size_bytes': s,
            'size_mb': round(s / 1048576, 3),
            'files': count_of(ap),
            'category': cat,
            'reason': reason,
            'references': refs,
            'confidence': conf,
        }
        if os.path.isfile(ap) and s < 8 * 1024 * 1024:
            entry['sha256'] = sha256(ap)
        manifest.append(entry)

    manifest.sort(key=lambda e: -e['size_bytes'])
    out = {
        'root': ROOT.replace('\\', '/'),
        'generated_at': '2026-10-04',
        'policy': 'Delete only confidence >= 0.95. Preserve A/B/C (runtime, source data, dev) and all AHSP/DED/AI critical data.',
        'entry_count': len(manifest),
        'total_bytes': total,
        'total_mb': round(total / 1048576, 2),
        'entries': manifest,
    }
    with open(os.path.join(ROOT, 'scripts', 'cleanup', 'cleanup-manifest-before-delete.json'), 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=1)

    print(f"MANIFEST: {len(manifest)} entries, {out['total_mb']:,.2f} MB")
    print()
    by_cat = {}
    for e in manifest:
        c = by_cat.setdefault(e['category'], [0, 0])
        c[0] += 1
        c[1] += e['size_bytes']
    for k in sorted(by_cat):
        n, b = by_cat[k]
        print(f"  {k:<16} {n:>4} entries  {b/1048576:>10,.2f} MB")
    print()
    for e in manifest:
        print(f"{e['size_mb']:>9,.3f} MB  [{e['category']:<12}] c={e['confidence']}  {e['path']}")

if __name__ == '__main__':
    main()
