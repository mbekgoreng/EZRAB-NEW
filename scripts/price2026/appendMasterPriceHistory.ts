/**
 * EZRAB PRICE 2026 — MASTER PRICING §4.4: INTERIM PRICE-HISTORY TRAIL
 * ====================================================================
 *
 * Appends a marker entry to the append-only interim audit trail:
 *   data/price2026/reports/master_price_history.jsonl
 *
 * Run:  npm run price:history
 *       (or: npx tsx scripts/price2026/appendMasterPriceHistory.ts)
 *
 * Behavior:
 *   - If the trail file does not exist, it is created with a HEADER
 *     line (schema version, master price version, record count, and
 *     the honest scope note) + one BASELINE entry describing the §4
 *     starting state. The BASELINE entry records NO price change —
 *     it marks the state the trail starts from.
 *   - If the file exists, one REGENERATION entry is appended (the
 *     pipeline regenerated priceMaster; per §4.4 the trail records
 *     every regeneration). The existing file is first parsed and
 *     validated — a corrupt trail refuses the append (fail-closed).
 *
 * This trail is an INTERIM audit trail, NOT a replacement for the
 * server-side master_price_history table
 * (supabase/migrations/20261116_master_price_governance.sql, NOT
 * APPLIED). Entries are never edited or deleted; corrections are new
 * entries. No prices are read, written, or changed by this script —
 * it only counts the current priceMaster records for the marker.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildHistoryEntry,
  buildHistoryJsonlHeader,
  parseHistoryJsonl,
  serializeHistoryEntryJsonl,
  serializeHistoryHeaderJsonl,
  validateHistoryEntries,
} from '../../src/engine/pricing/admin/masterPriceHistory';
import { MASTER_PRICE_VERSION } from '../../src/data/priceDatabase2026/types';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..', '..');
const REPORTS_DIR = path.join(ROOT, 'data', 'price2026', 'reports');
const TRAIL_PATH = path.join(REPORTS_DIR, 'master_price_history.jsonl');
const PRICE_MASTER_PATH = path.join(ROOT, 'data', 'price2026', 'validated', 'price_master.json');

function readPriceMasterCount(): number {
  const raw = fs.readFileSync(PRICE_MASTER_PATH, 'utf8');
  const data = JSON.parse(raw) as { count?: number; records?: unknown[] };
  if (typeof data.count === 'number') return data.count;
  if (Array.isArray(data.records)) return data.records.length;
  throw new Error('price_master.json has neither count nor records');
}

function main(): void {
  const now = new Date().toISOString();
  const recordCount = readPriceMasterCount();
  fs.mkdirSync(REPORTS_DIR, { recursive: true });

  if (!fs.existsSync(TRAIL_PATH)) {
    const header = buildHistoryJsonlHeader(now, recordCount, MASTER_PRICE_VERSION);
    const baseline = buildHistoryEntry({
      priceRecordId: null,
      resourceId: null,
      operation: 'BASELINE',
      previousAmount: null,
      newAmount: null,
      previousUnit: null,
      newUnit: null,
      previousRegion: null,
      newRegion: null,
      sourceKey: null,
      sourceTier: null,
      sourceDocument: null,
      verificationStatus: null,
      adminIdentity: null,
      changedAt: now,
      reason:
        `Master Pricing §4 baseline: interim history trail starts at master price version ` +
        `${MASTER_PRICE_VERSION} with ${recordCount} priceMaster records. No price changed in §4.`,
      affectedAhspReferences: [],
      affectedLivePriceProjects: [],
      publicationStatus: 'PUBLISHED',
      previousVersion: null,
      newVersion: null,
      masterPriceVersion: MASTER_PRICE_VERSION,
    });
    fs.writeFileSync(
      TRAIL_PATH,
      `${serializeHistoryHeaderJsonl(header)}\n${serializeHistoryEntryJsonl(baseline)}\n`,
      'utf8',
    );
    console.log(`Created: data/price2026/reports/master_price_history.jsonl (HEADER + BASELINE, ${recordCount} records)`);
    return;
  }

  const existing = fs.readFileSync(TRAIL_PATH, 'utf8');
  const parsed = parseHistoryJsonl(existing);
  if (parsed.errors.length > 0) {
    throw new Error(
      `Refusing to append: existing trail has ${parsed.errors.length} parse error(s): ${parsed.errors.join('; ')}`,
    );
  }
  const validation = validateHistoryEntries(parsed.entries);
  if (!validation.valid) {
    throw new Error(`Refusing to append: existing trail failed validation: ${validation.errors.join('; ')}`);
  }
  const marker = buildHistoryEntry({
    priceRecordId: null,
    resourceId: null,
    operation: 'REGENERATION',
    previousAmount: null,
    newAmount: null,
    previousUnit: null,
    newUnit: null,
    previousRegion: null,
    newRegion: null,
    sourceKey: null,
    sourceTier: null,
    sourceDocument: null,
    verificationStatus: null,
    adminIdentity: null,
    changedAt: now,
    reason:
      `priceMaster regenerated by the pipeline at master price version ` +
      `${MASTER_PRICE_VERSION} (${recordCount} records). Per-record changes are recorded by the server history once it exists.`,
    affectedAhspReferences: [],
    affectedLivePriceProjects: [],
    publicationStatus: 'PUBLISHED',
    previousVersion: null,
    newVersion: null,
    masterPriceVersion: MASTER_PRICE_VERSION,
  });
  fs.appendFileSync(TRAIL_PATH, `${serializeHistoryEntryJsonl(marker)}\n`, 'utf8');
  console.log(`Appended REGENERATION marker to data/price2026/reports/master_price_history.jsonl (${recordCount} records)`);
}

main();
