/**
 * MASTER PRICING §4.4 — PRICE HISTORY (pure writer + interim JSONL trail).
 * =======================================================================
 *
 * Price history is NEW — nothing like it exists today (the only history
 * in the repo is the project-override audit trail, capped at 100
 * localStorage entries, and the SQL-only price_assumption_history /
 * market_price_history tables). This module is the LOCAL, deterministic
 * writer for master-price history. The durable server-side history is
 * the `master_price_history` table in
 * supabase/migrations/20261116_master_price_governance.sql (trigger
 * SECURITY DEFINER + RLS insert-only) — NOT APPLIED yet, so the server
 * history does not exist either.
 *
 * APPEND-ONLY, in three layers:
 *   1. LOCAL (this module): entries are frozen objects; the only
 *      operation is `appendHistoryEntry` (returns a NEW array, refuses
 *      duplicate ids). There is NO update/delete function in this
 *      module — the test suite pins the exported API surface.
 *   2. INTERIM TRAIL: append-only JSONL at
 *      data/price2026/reports/master_price_history.jsonl — one entry
 *      per line, written per regeneration by
 *      scripts/price2026/appendMasterPriceHistory.ts. This is an
 *      honest TEMPORARY audit trail, NOT a replacement for the server
 *      history (documented in the file header + the §4 report).
 *   3. SERVER (future): RLS insert-only + no UPDATE/DELETE policies —
 *      see the migration. Real enforcement waits for that.
 *
 * Identity honesty: `adminIdentity` is the authenticated admin's
 * auth.users id, or NULL when there is no authentication. This module
 * takes the identity as INPUT and never verifies it — verification is
 * the (blocked) server's job. Passing a fabricated string here proves
 * nothing, because this module never persists to a server.
 *
 * Impact fields (`affectedAhspReferences`, `affectedLivePriceProjects`)
 * are INPUTS, computed by the caller — the real impact calculator is
 * §9. An empty list means "not computed / none known", never a claim
 * of zero impact; the §9 engine fills these in.
 */
import type {
  PriceLocation,
  PriceSourceTier,
  PriceVerificationStatus,
} from '../../../data/priceDatabase2026/types';
import { MASTER_PRICE_VERSION } from '../../../data/priceDatabase2026/types';
import { MASTER_PRICE_REASON_MIN_LENGTH } from './masterPriceRecord';

/** Schema version of one history entry (bumped only with a migration). */
export const MASTER_PRICE_HISTORY_SCHEMA_VERSION = 1 as const;

export type MasterPriceHistoryOperation =
  | 'BASELINE' // marker: the §4 starting state (no price change)
  | 'REGENERATION' // marker: priceMaster regenerated by the pipeline
  | 'CREATE'
  | 'UPDATE'
  | 'DEACTIVATE'
  | 'PUBLISH'
  | 'ROLLBACK';

export type MasterPricePublicationStatus = 'DRAFT' | 'PUBLISHED' | 'ROLLED_BACK' | 'SUPERSEDED';

/** Every §4.4 field, in one entry. Amounts are `number | null` — a missing price stays null. */
export interface MasterPriceHistoryEntry {
  /** Deterministic content-hash id: `MPH-<16 hex>` — same input, same id (idempotent re-writes). */
  id: string;
  schemaVersion: typeof MASTER_PRICE_HISTORY_SCHEMA_VERSION;
  /** Null for BASELINE / REGENERATION markers (no single record changed). */
  priceRecordId: string | null;
  /** Canonical entity (RES-xxx); null for markers. */
  resourceId: string | null;
  operation: MasterPriceHistoryOperation;
  previousAmount: number | null;
  newAmount: number | null;
  previousUnit: string | null;
  newUnit: string | null;
  previousRegion: PriceLocation | null;
  newRegion: PriceLocation | null;
  /** Source + provenance snapshot at change time. */
  sourceKey: string | null;
  sourceTier: PriceSourceTier | null;
  sourceDocument: string | null;
  verificationStatus: PriceVerificationStatus | null;
  /** Authenticated admin id, or NULL (honest no-auth). Never fabricated. */
  adminIdentity: string | null;
  /** ISO timestamp of the change. */
  changedAt: string;
  /** Required reason for the change (>= 10 chars, mirrors price_assumptions). */
  reason: string;
  /** AHSP codes whose components link to this record (§9 computes these). */
  affectedAhspReferences: string[];
  /** LIVE_MASTER_PRICE project ids affected (§9 computes these). */
  affectedLivePriceProjects: string[];
  publicationStatus: MasterPricePublicationStatus;
  previousVersion: number | null;
  newVersion: number | null;
  /** Master price DB version AFTER this change (e.g. '2026.1'). */
  masterPriceVersion: string;
}

export type MasterPriceHistoryInput = Omit<MasterPriceHistoryEntry, 'id' | 'schemaVersion'>;

// ---------------------------------------------------------------------------
// Deterministic id (FNV-1a 64-bit, hex) — pure, no dependency
// ---------------------------------------------------------------------------

function fnv1aHex(input: string): string {
  let hash = 0xcbf29ce484222325n;
  const prime = 0x100000001b3n;
  const mask = 0xffffffffffffffffn;
  for (let i = 0; i < input.length; i++) {
    hash ^= BigInt(input.charCodeAt(i));
    hash = (hash * prime) & mask;
  }
  return hash.toString(16).padStart(16, '0');
}

function entryIdFor(input: MasterPriceHistoryInput): string {
  const canonical = JSON.stringify([
    input.operation,
    input.priceRecordId,
    input.resourceId,
    input.previousAmount,
    input.newAmount,
    input.previousUnit,
    input.newUnit,
    input.previousRegion,
    input.newRegion,
    input.sourceKey,
    input.changedAt,
    input.reason,
    input.previousVersion,
    input.newVersion,
  ]);
  return `MPH-${fnv1aHex(canonical)}`;
}

// ---------------------------------------------------------------------------
// Builder (validates; freezes the entry so it cannot be rewritten in memory)
// ---------------------------------------------------------------------------

export function buildHistoryEntry(input: MasterPriceHistoryInput): MasterPriceHistoryEntry {
  if (typeof input.reason !== 'string' || input.reason.trim().length < MASTER_PRICE_REASON_MIN_LENGTH) {
    throw new Error(
      `History reason is required (at least ${MASTER_PRICE_REASON_MIN_LENGTH} characters)`,
    );
  }
  if (typeof input.changedAt !== 'string' || Number.isNaN(Date.parse(input.changedAt))) {
    throw new Error(`changedAt must be a valid ISO timestamp, got ${JSON.stringify(input.changedAt)}`);
  }
  for (const [field, value] of [
    ['previousAmount', input.previousAmount],
    ['newAmount', input.newAmount],
  ] as const) {
    if (value !== null && (typeof value !== 'number' || !Number.isFinite(value) || value < 0)) {
      throw new Error(`${field} must be null (unresolved) or a finite number >= 0`);
    }
  }
  if (!Array.isArray(input.affectedAhspReferences) || !Array.isArray(input.affectedLivePriceProjects)) {
    throw new Error('affectedAhspReferences and affectedLivePriceProjects must be arrays');
  }
  const entry: MasterPriceHistoryEntry = Object.freeze({
    ...input,
    id: entryIdFor(input),
    schemaVersion: MASTER_PRICE_HISTORY_SCHEMA_VERSION,
    affectedAhspReferences: freezeArray(input.affectedAhspReferences),
    affectedLivePriceProjects: freezeArray(input.affectedLivePriceProjects),
    previousRegion: input.previousRegion ? Object.freeze({ ...input.previousRegion }) : null,
    newRegion: input.newRegion ? Object.freeze({ ...input.newRegion }) : null,
  });
  return entry;
}

/**
 * Freeze a copy of an array and keep its mutable element type.
 * (Object.freeze alone returns `readonly T[]`, which is not
 * assignable to `T[]` — the cast is the documented escape: the array
 * IS frozen at runtime, so no caller can push to it.)
 */
function freezeArray<T>(arr: readonly T[]): T[] {
  return Object.freeze([...arr]) as T[];
}

/**
 * Append-only write: returns a NEW (frozen) array with the entry
 * appended. Refuses a duplicate id (idempotency: re-appending the
 * same entry is an error, not a silent second row). Never mutates the
 * input array. There is intentionally no update or delete operation.
 */
export function appendHistoryEntry(
  entries: readonly MasterPriceHistoryEntry[],
  entry: MasterPriceHistoryEntry,
): readonly MasterPriceHistoryEntry[] {
  if (entries.some((e) => e.id === entry.id)) {
    throw new Error(`Duplicate history entry id ${entry.id} — history is append-only, re-append refused`);
  }
  return Object.freeze([...entries, entry]);
}

/** Validate a history chain: unique ids, required fields, sane amounts. */
export function validateHistoryEntries(
  entries: readonly MasterPriceHistoryEntry[],
): { valid: boolean; errors: string[] } {
  const errors: string[] = [];
  const seen = new Set<string>();
  entries.forEach((e, i) => {
    const where = `entry[${i}]${e.id ? ` ${e.id}` : ''}`;
    if (!e.id) errors.push(`${where}: missing id`);
    else if (seen.has(e.id)) errors.push(`${where}: duplicate id`);
    else seen.add(e.id);
    if (e.schemaVersion !== MASTER_PRICE_HISTORY_SCHEMA_VERSION) {
      errors.push(`${where}: unexpected schemaVersion ${String(e.schemaVersion)}`);
    }
    if (typeof e.reason !== 'string' || e.reason.trim().length < MASTER_PRICE_REASON_MIN_LENGTH) {
      errors.push(`${where}: reason too short or missing`);
    }
    if (typeof e.changedAt !== 'string' || Number.isNaN(Date.parse(e.changedAt))) {
      errors.push(`${where}: changedAt is not a valid ISO timestamp`);
    }
    for (const [field, value] of [
      ['previousAmount', e.previousAmount],
      ['newAmount', e.newAmount],
    ] as const) {
      if (value !== null && (typeof value !== 'number' || !Number.isFinite(value) || value < 0)) {
        errors.push(`${where}: ${field} must be null or a finite number >= 0`);
      }
    }
  });
  return { valid: errors.length === 0, errors };
}

// ---------------------------------------------------------------------------
// Interim JSONL trail (data/price2026/reports/master_price_history.jsonl)
// ---------------------------------------------------------------------------

export interface MasterPriceHistoryJsonlHeader {
  kind: 'HEADER';
  schemaVersion: typeof MASTER_PRICE_HISTORY_SCHEMA_VERSION;
  generatedAt: string;
  masterPriceVersion: string;
  recordCount: number;
  /** Honest scope statement — this file is an interim trail, not the server history. */
  note: string;
}

export const MASTER_PRICE_HISTORY_JSONL_NOTE =
  'INTERIM AUDIT TRAIL (Master Pricing §4.4): append-only JSONL written per regeneration. ' +
  'This is a temporary, honest audit trail — NOT a replacement for the server-side ' +
  'master_price_history table (supabase/migrations/20261116_master_price_governance.sql, NOT APPLIED). ' +
  'Entries are never edited or deleted; corrections are new entries.';

/** Build the header line for a fresh trail file. */
export function buildHistoryJsonlHeader(
  generatedAt: string,
  recordCount: number,
  masterPriceVersion: string = MASTER_PRICE_VERSION,
): MasterPriceHistoryJsonlHeader {
  return {
    kind: 'HEADER',
    schemaVersion: MASTER_PRICE_HISTORY_SCHEMA_VERSION,
    generatedAt,
    masterPriceVersion,
    recordCount,
    note: MASTER_PRICE_HISTORY_JSONL_NOTE,
  };
}

/** Serialize one entry as a single JSONL line. */
export function serializeHistoryEntryJsonl(entry: MasterPriceHistoryEntry): string {
  return JSON.stringify(entry);
}

/** Serialize the header as a single JSONL line. */
export function serializeHistoryHeaderJsonl(header: MasterPriceHistoryJsonlHeader): string {
  return JSON.stringify(header);
}

export interface ParsedHistoryJsonl {
  header: MasterPriceHistoryJsonlHeader | null;
  entries: MasterPriceHistoryEntry[];
  /** Line-level parse errors (line numbers are 1-based). Never silently skipped. */
  errors: string[];
}

/** Parse a JSONL trail file. Malformed lines are reported, never silently dropped. */
export function parseHistoryJsonl(text: string): ParsedHistoryJsonl {
  let parsedHeader: MasterPriceHistoryJsonlHeader | null = null;
  const entries: MasterPriceHistoryEntry[] = [];
  const errors: string[] = [];
  const lines = text.split('\n').filter((l) => l.trim() !== '');
  lines.forEach((line, idx) => {
    const lineNo = idx + 1;
    let obj: unknown;
    try {
      obj = JSON.parse(line);
    } catch {
      errors.push(`line ${lineNo}: invalid JSON`);
      return;
    }
    if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) {
      errors.push(`line ${lineNo}: not a JSON object`);
      return;
    }
    const rec = obj as Record<string, unknown>;
    if (rec.kind === 'HEADER') {
      if (parsedHeader !== null) errors.push(`line ${lineNo}: duplicate HEADER`);
      else parsedHeader = obj as MasterPriceHistoryJsonlHeader;
      return;
    }
    if (typeof rec.id !== 'string' || typeof rec.operation !== 'string') {
      errors.push(`line ${lineNo}: history entry without id/operation`);
      return;
    }
    entries.push(obj as MasterPriceHistoryEntry);
  });
  return { header: parsedHeader, entries, errors };
}
